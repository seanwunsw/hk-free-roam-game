"""Remove the placeholder player model and every reference to it.

    python tools/characters/remove_placeholder.py --dry-run   # show what would change
    python tools/characters/remove_placeholder.py             # do it
    python tools/characters/remove_placeholder.py --check     # only look for leftovers

What it does:
1. Deletes data/characters/placeholder/ (the model file, its README).
2. Drops the "placeholder_model" key from data/config/player.json.
3. Cuts the block between the BEGIN/END placeholder-credit markers out of
   data/characters/CREDITS.md.
4. Deletes the baked copy, UnrealProject/Content/HK/Player/ (regenerated by
   the next bake). Skip with --keep-baked.
5. Searches tracked files for the placeholder's name and URL id and exits 1
   if anything is left.

It never touches git history and never commits. Review with `git status`
and commit yourself.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def set_root(root: Path) -> None:
    global ROOT, PLACEHOLDER_DIR, CONFIG, CREDITS, BAKED
    ROOT = root.resolve()
    PLACEHOLDER_DIR = ROOT / "data" / "characters" / "placeholder"
    CONFIG = ROOT / "data" / "config" / "player.json"
    CREDITS = ROOT / "data" / "characters" / "CREDITS.md"
    BAKED = ROOT / "UnrealProject" / "Content" / "HK" / "Player"


set_root(ROOT)
CONFIG_KEY = "placeholder_model"
BLOCK_RE = re.compile(
    r"\n?<!-- BEGIN placeholder-credit -->.*?<!-- END placeholder-credit -->\n?",
    re.S,
)
# Strings that only the placeholder uses. This file and the swap guide name
# them on purpose, so they are excluded from the search.
LEFTOVER_PATTERNS = ["cute_chibi", "cute chibi", "tim0", "28e2f98ab4bf4313a3f258d45d987716"]
SEARCH_EXCLUDE = {"tools/characters/remove_placeholder.py", "data/characters/README.md"}


def tracked_files() -> list[Path]:
    try:
        out = subprocess.run(
            ["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True
        ).stdout.decode("utf-8")
        return [ROOT / p for p in out.split("\0") if p]
    except (OSError, subprocess.CalledProcessError):
        return [p for p in ROOT.rglob("*") if p.is_file() and ".git" not in p.parts]


def find_leftovers() -> list[str]:
    hits = []
    for path in tracked_files():
        rel = path.relative_to(ROOT).as_posix()
        if rel in SEARCH_EXCLUDE or not path.is_file():
            continue
        lower_rel = rel.lower()
        if any(p in lower_rel for p in LEFTOVER_PATTERNS):
            hits.append(f"{rel}: file name")
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for n, line in enumerate(text.splitlines(), 1):
            low = line.lower()
            if any(p in low for p in LEFTOVER_PATTERNS):
                hits.append(f"{rel}:{n}: {line.strip()[:120]}")
    return hits


def remove(dry_run: bool, keep_baked: bool) -> list[str]:
    actions = []
    if PLACEHOLDER_DIR.exists():
        actions.append(f"delete {PLACEHOLDER_DIR.relative_to(ROOT)}/")
        if not dry_run:
            shutil.rmtree(PLACEHOLDER_DIR)

    if CONFIG.exists():
        cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
        if CONFIG_KEY in cfg:
            actions.append(f'remove "{CONFIG_KEY}" from {CONFIG.relative_to(ROOT)}')
            if not dry_run:
                del cfg[CONFIG_KEY]
                CONFIG.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    if CREDITS.exists():
        text = CREDITS.read_text(encoding="utf-8")
        new = BLOCK_RE.sub("\n", text).rstrip() + "\n"
        if new != text:
            actions.append(f"cut placeholder-credit block from {CREDITS.relative_to(ROOT)}")
            if not dry_run:
                CREDITS.write_text(new, encoding="utf-8")

    if BAKED.exists() and not keep_baked:
        actions.append(f"delete baked {BAKED.relative_to(ROOT)}/ (the next bake rebuilds it)")
        if not dry_run:
            shutil.rmtree(BAKED)
    return actions


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Remove the placeholder player model.")
    parser.add_argument("--dry-run", action="store_true", help="print the plan, change nothing")
    parser.add_argument("--check", action="store_true", help="only search for leftovers")
    parser.add_argument("--keep-baked", action="store_true", help="keep UnrealProject/Content/HK/Player")
    parser.add_argument("--root", type=Path, default=ROOT, help="repo root (default: this checkout)")
    args = parser.parse_args(argv)
    set_root(args.root)

    if not args.check:
        actions = remove(args.dry_run, args.keep_baked)
        prefix = "would " if args.dry_run else ""
        for a in actions or ["nothing to remove"]:
            print(prefix + a)
        if args.dry_run:
            return 0

    hits = find_leftovers()
    if hits:
        print("Placeholder references still found:")
        for h in hits:
            print("  " + h)
        return 1
    print("No placeholder references left in tracked files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
